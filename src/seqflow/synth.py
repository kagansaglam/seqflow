"""Synthetic file-set generator for benchmarking bulk file operations.

The content is random bytes under FASTQ-like names. It is NOT sequencing data;
any result obtained with it must be described as synthetic.
"""
from __future__ import annotations

import random
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

MARKER = "SYNTHETIC.txt"
PROGRESS_EVERY = 500


@dataclass
class SynthSummary:
    root: str
    n_files: int
    total_bytes: int
    seed: int


def generate_fileset(root: str | Path, n_files: int, *, min_bytes: int = 50_000,
                     max_bytes: int = 500_000, seed: int = 0, files_per_dir: int = 100,
                     paired: bool = False,
                     progress: Callable[[int, int], None] | None = None) -> SynthSummary:
    """Create n_files deterministic pseudo-random .fastq.gz files in batch_NNNN/ folders.

    Same arguments and seed always give byte-identical files, so runs are comparable.
    """
    if n_files <= 0:
        raise ValueError("n_files must be positive")
    if min_bytes < 0 or min_bytes > max_bytes:
        raise ValueError("need 0 <= min_bytes <= max_bytes")
    if files_per_dir <= 0:
        raise ValueError("files_per_dir must be positive")

    rng = random.Random(seed)
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    total = 0
    for i in range(n_files):
        folder = root / f"batch_{i // files_per_dir:04d}"
        folder.mkdir(exist_ok=True)
        sample = i // 2 if paired else i
        read = "R2" if paired and i % 2 else "R1"
        size = rng.randint(min_bytes, max_bytes)
        (folder / f"S{sample:06d}_{read}.fastq.gz").write_bytes(rng.randbytes(size))
        total += size
        if progress and ((i + 1) % PROGRESS_EVERY == 0 or i + 1 == n_files):
            progress(i + 1, n_files)
    (root / MARKER).write_text(
        f"Synthetic random data generated by seqflow (seed={seed}). Not sequencing data.\n"
    )
    return SynthSummary(root=str(root), n_files=n_files, total_bytes=total, seed=seed)
